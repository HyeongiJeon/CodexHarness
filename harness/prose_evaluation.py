"""Small offline scorer for actual Codex natural-prose trials, not an LLM.

The oracle is read only by score(), after actor outputs have been frozen.
No model responses or semantic interpretations are generated by this module.
"""
from __future__ import annotations

from decimal import Decimal, InvalidOperation
import json
from pathlib import Path
import shutil

from .evidence import check_citations, serialized
from .roles import ROOT
from .sources import hash_file


def prepare(work: Path, fixture: Path = ROOT/'fixtures/prose') -> dict:
    work=work.resolve(); inputs=work/'inputs'
    if inputs.exists():
        raise FileExistsError('Refusing to overwrite existing evaluation inputs')
    inputs.mkdir(parents=True)
    shutil.copytree(fixture/'corpus',inputs/'corpus')
    shutil.copyfile(fixture/'questions.json',inputs/'questions.json')
    (work/'packs').mkdir();(work/'outputs').mkdir()
    files=sorted((inputs/'corpus').rglob('*'))
    manifest={'documents':[{ 'path':p.relative_to(inputs).as_posix(),'sha256':hash_file(p),'bytes':p.stat().st_size} for p in files if p.is_file()],
              'question_hash':hash_file(inputs/'questions.json'),
              'actor_inputs':['inputs/corpus/','inputs/questions.json'],
              'limitations':['Input separation is a task boundary on a shared filesystem, not an OS access-control sandbox.']}
    (work/'manifest.json').write_text(serialized(manifest))
    return manifest


def _equal(actual, expected) -> bool:
    if isinstance(expected,bool) or expected is None:
        return actual is expected
    if isinstance(actual,bool) or actual is None:
        return False
    try:
        a,b=Decimal(str(actual)),Decimal(str(expected))
        return a.is_finite() and b.is_finite() and a==b
    except InvalidOperation:
        return actual==expected


def _anchors(anchors: list[dict], entries: list[dict]) -> list[bool]:
    return [any(e.get('relative_path')==a['document'] and a['contains'] in e.get('excerpt','') for e in entries) for a in anchors]


def score(work: Path, oracle: dict, answers: dict, audit: dict | None = None) -> dict:
    """Score scalar/status correctness separately from retrieval and citations.

    Arbitrary answer prose is NOT semantically graded by Python. A real,
    independent auditor must inspect those claims against original sources.
    """
    work=work.resolve()
    manifest=json.loads((work/'manifest.json').read_text())
    expected_files={entry['path'] for entry in manifest['documents']}
    current_files={p.relative_to(work/'inputs').as_posix() for p in (work/'inputs/corpus').rglob('*') if p.is_file()}
    if (expected_files!=current_files or hash_file(work/'inputs/questions.json')!=manifest['question_hash'] or any(
            hash_file(work/'inputs'/entry['path'])!=entry['sha256'] for entry in manifest['documents'])):
        raise ValueError('Frozen evaluation inputs changed; trial is invalid')
    ledger=json.loads((work/'retrieval.json').read_text())
    retrieval={q['id']:q for q in ledger['questions']}
    response={q['question_id']:q for q in answers['answers']}
    if len(response)!=len(answers['answers']):
        raise ValueError('Duplicate answer question IDs invalidate the trial')
    audited={q['question_id']:q for q in (audit or {}).get('questions',[])}
    results=[]
    metrics={key:0 for key in ('questions','correct_answers','wrong_answers','correct_abstentions','correct_conflict_judgments',
        'wrong_abstentions','false_definitive_conclusions','retrieval_failures','pack_selection_failures','synthesis_failures',
        'source_verification_failures','required_evidence_found','required_evidence_total','pack_evidence_found',
        'citations_verified','citations_total','exception_condition_omissions','exception_condition_errors','conflicts_detected',
        'audit_false_acceptances','audit_caught_false_certainties','audit_false_rejections','audited_questions')}
    for gold in oracle['questions']:
        qid=gold['id'];row=retrieval.get(qid,{})
        pack_path=(work/row.get('pack',f'packs/{qid}.json')).resolve()
        if not pack_path.is_relative_to(work):raise ValueError('Pack must be inside trial workspace')
        pack=json.loads(pack_path.read_text())
        candidates=[e for search in row.get('searches',[]) for e in search.get('results',[])]
        anchors=gold.get('required_evidence',[])
        retrieval_hits=_anchors(anchors,candidates);pack_hits=_anchors(anchors,pack['evidence'])
        actual=response.get(qid,{})
        expected=gold.get('expected_values',{})
        values=actual.get('values',{})
        values_ok=all(k in values and _equal(values[k],v) for k,v in expected.items())
        status=actual.get('status');expected_status=gold['expected_status']
        semantic_ok=status==expected_status and values_ok
        if expected_status=='insufficient_evidence':semantic_ok=semantic_ok and bool(actual.get('missing_evidence'))
        if expected_status=='conflict':semantic_ok=semantic_ok and bool(actual.get('conflicts'))
        cited=actual.get('citations',[])
        by_id={e.get('citation_id',e['evidence_id']):e for e in pack['evidence']}
        selected=[by_id[c] for c in cited if isinstance(c,str) and c in by_id]
        gate=check_citations(pack,cited)
        quote_audit=gate['verification'];verified=len(selected)-len(gate['unverified_or_metadata_changed'])
        # truncation/completeness is a separate pack property, not a citation-source failure
        sources_ok=bool(cited) and not gate['missing_from_pack'] and not gate['unverified_or_metadata_changed']
        supported_complete=gate['pack_complete']
        citation_hits=_anchors(anchors,selected)
        grounded=semantic_ok and sources_ok and supported_complete and all(citation_hits)
        false_certain=status=='supported' and not grounded
        rfail=not all(retrieval_hits);pfail=all(retrieval_hits) and not all(pack_hits)
        sfail=all(pack_hits) and not semantic_ok
        audit_row=audited.get(qid,{})
        audit_accept=audit_row.get('supported_by_sources')
        condition_keys=gold.get('condition_value_keys',[])
        condition_omissions=sum(k not in values for k in condition_keys)
        condition_errors=sum(k in values and not _equal(values[k],expected[k]) for k in condition_keys)
        counts={'questions':1,'correct_answers':int(expected_status=='supported' and semantic_ok),
          'wrong_answers':int(not semantic_ok),'correct_abstentions':int(expected_status=='insufficient_evidence' and semantic_ok),
          'correct_conflict_judgments':int(expected_status=='conflict' and semantic_ok),
          'wrong_abstentions':int(status=='insufficient_evidence' and expected_status!='insufficient_evidence'),
          'false_definitive_conclusions':int(false_certain),'retrieval_failures':int(rfail),'pack_selection_failures':int(pfail),
          'synthesis_failures':int(sfail),'source_verification_failures':int(not sources_ok),
          'required_evidence_found':sum(retrieval_hits),'required_evidence_total':len(anchors),'pack_evidence_found':sum(pack_hits),
          'citations_verified':verified,'citations_total':len(cited),'exception_condition_omissions':condition_omissions,
          'exception_condition_errors':condition_errors,
          'conflicts_detected':int(expected_status=='conflict' and status=='conflict' and bool(actual.get('conflicts'))),
          'audit_false_acceptances':int(false_certain and audit_accept is True),
          'audit_caught_false_certainties':int(false_certain and audit_accept is False),
          'audit_false_rejections':int(grounded and audit_accept is False),'audited_questions':int(isinstance(audit_accept,bool))}
        for key,value in counts.items():metrics[key]+=value
        results.append({'id':qid,'expected_status':expected_status,'actual_status':status,'answer_correct':semantic_ok,
            'grounded':grounded,'false_definitive':false_certain,'retrieval_failure':rfail,'pack_selection_failure':pfail,
            'synthesis_failure':sfail,'source_verification_failure':not sources_ok,'required_anchor_retrieval':retrieval_hits,
            'required_anchor_pack':pack_hits,'required_anchor_citations':citation_hits,'quote_verification':quote_audit,
            'pack_chars':len(serialized(pack)),'pack_truncated':pack.get('truncated'),'audit_supported':audit_accept})
    metrics['required_evidence_search_rate']=metrics['required_evidence_found']/max(metrics['required_evidence_total'],1)
    metrics['citation_source_accuracy']=metrics['citations_verified']/max(metrics['citations_total'],1)
    return {'metrics':metrics,'questions':results,'evaluation_scope':[
        'Status and requested named values are scored against an isolated oracle after actors finish.',
        'Required original-text anchors measure retrieval, pack selection and citation support independently.',
        'Quote verification is literal provenance. Natural-language semantic claims require independent Codex audit.',
        'One synthetic trial is not an estimate of general Korean QA accuracy.']}
